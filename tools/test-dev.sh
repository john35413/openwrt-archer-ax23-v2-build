#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-2.0-or-later
# ./tools/test-dev.sh [static|unit|network|all|twin]   (default: all; twin is opt-in)
# Writes logs/test-<suite>.log and a combined reports/test-summary.tsv.
# None of these suites touches a router. "network" is a SIMULATION.
set -u
PROJ="$(cd "$(dirname "$0")/.." && pwd)"; cd "$PROJ" || exit 1
SUITE="${1:-all}"; SUM="$PROJ/reports/test-summary.tsv"; mkdir -p logs reports
: >"$SUM"; total_fail=0
run() {	# run name cmd...
	local n="$1"; shift; echo "== $n"
	"$@" >"logs/test-$n.log" 2>&1; local rc=$?
	grep -E "^(PASS|FAIL|SKIP)|^N[0-9]+ |^ok|^FAIL|SUMMARY| ... ok$| ... FAIL| ... ERROR" "logs/test-$n.log" | sed 's/^/   /' | tail -60
	case $rc in 0) st=PASS ;; 77) st=SKIP ;; *) st=FAIL; total_fail=$((total_fail+1)) ;; esac
	printf '%s\t%s\t%s\n' "$n" "$st" "logs/test-$n.log" >>"$SUM"; echo "   -> $st"
	return "$rc"
}
case "$SUITE" in static|all) run static tests/static/run-static.sh ;; esac
case "$SUITE" in unit|all)
	run unit-python python3 -W ignore -I tests/unit/test_tools.py -v
	run unit-ath11k-rings python3 -W ignore -I tests/unit/test_ath11k_rings.py -v
	run unit-caldata bash tests/unit/test_caldata_regdomain.sh
	run unit-mac bash tests/unit/test_mac_derivation.sh
	run unit-bdf-extract bash tests/unit/test_bdf_extract.sh
	run unit-selfdiag-readonly bash tests/unit/test_selfdiag_readonly.sh
	run unit-radio-profile bash tests/unit/test_radio_profile.sh
	run unit-mpd-recovery bash tests/unit/test_mpd_recovery.sh
	run unit-ath11k-ring-alloc bash tests/unit/test_ath11k_ring_alloc.sh
	run unit-trunk-variant bash tests/unit/test_trunk_variant.sh
	run unit-selfdiag-boardid bash tests/unit/test_selfdiag_boardid.sh
	run unit-selfdiag-calregions bash tests/unit/test_selfdiag_calregions.sh
	run unit-clean-symlink-guard bash tests/unit/test_clean_symlink_guard.sh
	run preboot-docs python3 -I tests/unit/test_preboot_gate.py -v ;; esac
case "$SUITE" in network|all)
	# Prefer the ruleset generated by the built dev image's own fw4.
	if run fw4-generate tests/network/gen-fw4-ruleset.sh dev "$PROJ/logs/network/fw4-generated-dev.nft"; then
		run network-sim tests/network/vm-run.sh --ruleset "$PROJ/logs/network/fw4-generated-dev.nft"
	else
		run network-sim tests/network/vm-run.sh
	fi ;; esac
case "$SUITE" in twin) run twin tests/twin/run-twin.sh ;; esac	# opt-in: ~25 min, needs ./tools/build-twin.sh
echo; column -t "$SUM"; [ $total_fail -eq 0 ]
